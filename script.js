function setText(id, value) {
  const element = document.getElementById(id);
  if (element) {
    element.textContent = value;
  }
}

function renderBulletList(targetId, items) {
  const target = document.getElementById(targetId);
  if (!target) {
    return;
  }

  target.innerHTML = items
    .map(
      (item) => `
        <div class="stacked-item">
          <p>${item}</p>
        </div>
      `
    )
    .join("");
}

function renderQuickFacts() {
  const target = document.getElementById("quick-facts");
  target.innerHTML = weddingDetails.quickFacts
    .map(
      (fact) => `
        <div class="fact-card">
          <span class="label">${fact.label}</span>
          <strong class="value">${fact.value}</strong>
        </div>
      `
    )
    .join("");
}

function renderStory() {
  const target = document.getElementById("story-content");
  target.innerHTML = weddingDetails.story
    .map((paragraph) => `<p>${paragraph}</p>`)
    .join("");
}

function renderWeddingParty() {
  const target = document.getElementById("wedding-party");
  target.innerHTML = weddingDetails.party
    .map(
      (person) => `
        <div class="stacked-item">
          <strong>${person.role}: ${person.name}</strong>
          <p>${person.note}</p>
        </div>
      `
    )
    .join("");
}

function renderTimeline() {
  const target = document.getElementById("timeline");
  target.innerHTML = weddingDetails.schedule
    .flatMap((day) =>
      day.events.map(
        (event) => `
          <article class="timeline-item">
            <div class="timeline-meta">
              <div class="timeline-day">${day.day}, ${day.date}</div>
              <div class="timeline-time">${event.time}</div>
            </div>
            <div>
              <h3>${event.title}</h3>
              <p><strong>Location:</strong> ${event.location}</p>
              <p>${event.description}</p>
            </div>
          </article>
        `
      )
    )
    .join("");
}

function renderDetailCard(targetId, detail) {
  const target = document.getElementById(targetId);
  target.innerHTML = `
    <p class="section-tag">Details</p>
    <h2>${detail.title}</h2>
    <div class="stacked-list">
      ${detail.items
        .map(
          (item) => `
            <div class="stacked-item">
              <p>${item}</p>
            </div>
          `
        )
        .join("")}
    </div>
  `;
}

function renderFaq() {
  const target = document.getElementById("faq-list");
  target.innerHTML = weddingDetails.faq
    .map(
      (item) => `
        <article class="faq-item">
          <h3>${item.question}</h3>
          <p>${item.answer}</p>
        </article>
      `
    )
    .join("");
}

function updateCountdown() {
  const now = new Date();
  const targetDate = new Date(weddingDetails.couple.countdownDate);
  const diff = targetDate - now;

  if (diff <= 0) {
    setText("days", "0");
    setText("hours", "0");
    setText("minutes", "0");
    return;
  }

  const minutesTotal = Math.floor(diff / 1000 / 60);
  const days = Math.floor(minutesTotal / (60 * 24));
  const hours = Math.floor((minutesTotal % (60 * 24)) / 60);
  const minutes = minutesTotal % 60;

  setText("days", String(days));
  setText("hours", String(hours));
  setText("minutes", String(minutes));
}

function initializePage() {
  setText("couple-names", weddingDetails.couple.names);
  setText("hero-date", weddingDetails.couple.date);
  setText("hero-location", weddingDetails.couple.venue);
  setText("hero-summary", weddingDetails.couple.summary);
  setText("intro-text", weddingDetails.couple.intro);
  setText("footer-note", weddingDetails.couple.footer);

  renderQuickFacts();
  renderStory();
  renderWeddingParty();
  renderTimeline();
  renderDetailCard("ceremony", weddingDetails.ceremony);
  renderDetailCard("reception", weddingDetails.reception);
  renderBulletList("travel-content", weddingDetails.travel);
  renderBulletList("stay-content", weddingDetails.stay);
  renderBulletList("menu-content", weddingDetails.menu);
  renderBulletList("attire-content", weddingDetails.attire);
  renderBulletList("registry-content", weddingDetails.registry);
  renderBulletList("accessibility-content", weddingDetails.accessibility);
  renderBulletList("weather-content", weddingDetails.weather);
  renderBulletList("rsvp-content", weddingDetails.rsvp);
  renderBulletList("contact-content", weddingDetails.contact);
  renderFaq();
  updateCountdown();
  window.setInterval(updateCountdown, 60000);
}

initializePage();
